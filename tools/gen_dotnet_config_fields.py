"""Sinh bảng khoá cấu hình cho bản .NET từ ``core/config.py`` (nguồn chuẩn duy nhất).

Ghi ra:
* ``dotnet/src/MuxStudio.Core/ConfigFields.cs``  — bảng ``Field`` + ``GROUPS`` cho C#
* ``dotnet/tests/MuxStudio.Core.Tests/Data/python_config.json`` — dữ liệu đối chiếu cho test C#
  (bảng khoá + ``json.dumps`` của cấu hình mặc định, để so từng byte ``config.json``)

Chạy lại mỗi khi sửa ``FIELDS`` trong ``core/config.py``:  ``python tools/gen_dotnet_config_fields.py``
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core import config as C  # noqa: E402

OUT_CS = ROOT / "dotnet" / "src" / "MuxStudio.Core" / "ConfigFields.cs"
OUT_JSON = ROOT / "dotnet" / "tests" / "MuxStudio.Core.Tests" / "Data" / "python_config.json"


def cs_str(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append(f"\\u{ord(ch):04x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def cs_value(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return f"{v}L"
    if isinstance(v, float):
        return repr(v) if ("." in repr(v) or "e" in repr(v)) else repr(v) + ".0"
    if isinstance(v, str):
        return cs_str(v)
    if isinstance(v, list):
        assert all(isinstance(x, str) for x in v), v
        return "new List<string> { " + ", ".join(cs_str(x) for x in v) + " }" if v else "new List<string>()"
    if isinstance(v, dict):
        assert not v, "chỉ hỗ trợ bảng rỗng làm mặc định"
        return "new OrderedDictionary<string, object?>(StringComparer.Ordinal)"
    raise TypeError(type(v))


def main() -> None:
    lines = [
        "// <auto-generated>",
        "// Sinh từ core/config.py bằng tools/gen_dotnet_config_fields.py — ĐỪNG sửa tay, sửa config.py rồi chạy lại.",
        "// </auto-generated>",
        "#nullable enable",
        "namespace MuxStudio.Core;",
        "",
        "public static partial class ConfigSchema",
        "{",
        "    /// <summary>Nhóm cài đặt (đúng thứ tự hiển thị).</summary>",
        "    public static readonly IReadOnlyList<(string Key, string Label)> Groups =",
        "    [",
    ]
    for k, label in C.GROUPS.items():
        lines.append(f"        ({cs_str(k)}, {cs_str(label)}),")
    lines += ["    ];", "", "    /// <summary>Bảng khoá cấu hình (= <c>FIELDS</c> của config.py, cùng thứ tự).</summary>",
              "    public static readonly IReadOnlyList<Field> Fields =", "    ["]
    for f in C.FIELDS:
        args = [cs_str(f.key), cs_value(f.default), cs_str(f.group), cs_str(f.label)]
        named = []
        if f.help:
            named.append(f"Help: {cs_str(f.help)}")
        if f.kind:
            named.append(f"Kind: {cs_str(f.kind)}")
        if f.choices:
            named.append("Choices: [" + ", ".join(cs_str(c) for c in f.choices) + "]")
        if f.advanced:
            named.append("Advanced: true")
        lines.append("        new(" + ", ".join(args + named) + "),")
    lines += ["    ];", "}", ""]
    OUT_CS.write_text("\r\n".join(lines), encoding="utf-8", newline="")

    data = {
        "groups": list(C.GROUPS.items()),
        "fields": [
            {"key": f.key, "default": f.default, "type": type(f.default).__name__, "group": f.group, "label": f.label,
             "help": f.help, "kind": f.kind, "choices": list(f.choices), "advanced": f.advanced}
            for f in C.FIELDS
        ],
        "default_config_json": json.dumps(C.Config().to_json_dict(), ensure_ascii=False, indent=2),
        "version": C.CONFIG_VERSION,
    }
    bats = [ROOT / "reference" / n for n in ("SubFetch_v30.bat", "SubPrep_v20.bat", "MuxTool_v17.bat")]
    if all(p.exists() for p in bats):
        imp = C.import_from_bat(bats)
        data["bat_import_reference"] = {
            "kinds": [k for _, k in imp.files],
            "values": {k: {"value": it.value, "source": it.source, "line": it.line} for k, it in imp.values.items()},
            "conflicts": {k: [x.value for x in v] for k, v in imp.conflicts.items()},
            "secrets": sorted(imp.secrets),
            "ignored": [list(x) for x in imp.ignored],
            "problems": [list(x) for x in imp.problems],
        }
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8", newline="")
    print(f"{len(C.FIELDS)} khoá -> {OUT_CS.relative_to(ROOT)}, {OUT_JSON.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
